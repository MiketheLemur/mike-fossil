"""Render investigation evidence as a readable Markdown report.

Template-based and deterministic: the same evidence always renders the same
report. An LLM narration layer may sit on top of evidence.json in the future;
it is not required for the report to be complete.
"""


def _verdict_headline(verdict):
    t = verdict.get("type", "inconclusive")
    c = verdict.get("confidence", "low")
    labels = {
        "direct_descendant": "Direct descendant / fork lineage",
        "acknowledged_derivation": "Acknowledged derivation",
        "likely_shared_code": "Likely shared code",
        "vendored_component": "Vendored component",
        "port_or_reimplementation": "Port / reimplementation",
        "no_meaningful_relationship": "No meaningful relationship found",
        "inconclusive": "Inconclusive",
    }
    return f"{labels.get(t, t)} (confidence: {c})"


def _fmt_list(items, empty="(none)"):
    if not items:
        return empty
    return "\n".join(f"- {x}" for x in items)


def _candidate_section(r):
    v = r["verdict"]
    kn = r.get("key_numbers", {})
    lines = [
        f"### {r['full_name']}",
        "",
        f"**Considered because:** {', '.join(r.get('via', [])) or '—'}",
        "",
        f"**Verdict:** {_verdict_headline(v)}",
        "",
        v.get("summary", ""),
        "",
    ]
    if kn:
        lines += ["Key numbers:", ""]
        for k in ("shared_commits", "identical_files", "identifier_jaccard",
                  "shared_rare_identifiers", "name_similarity", "dep_overlap",
                  "timeline"):
            if k in kn:
                lines.append(f"- {k}: {kn[k]}")
        lines.append("")
    unc = v.get("uncertainty") or []
    if unc:
        lines += ["Uncertainty:", ""]
        lines += [f"- {u}" for u in unc if u]
        lines.append("")
    return "\n".join(lines)


def _compare_detail(ev):
    comp = ev.get("comparison")
    if not comp:
        return ""
    a, b = ev["a"]["label"], ev["b"]["label"]
    lines = ["## Evidence detail", ""]
    ie = comp["identical_same_path"]
    lines.append(f"Byte-identical files at the same path: **{ie['count']}**")
    if ie["examples"]:
        lines += [""] + [f"- `{p}`" for p in ie["examples"][:10]] + [""]
    mv = comp["identical_diff_path"]
    lines.append(f"Byte-identical files at different paths (moves/renames): **{mv['count']}**")
    if mv["examples"]:
        lines += [""] + [f"- `{p}`" for p in mv["examples"][:10]] + [""]
    vs = comp["very_similar_files"]
    lines.append(f"Very similar files (shingle similarity ≥ 0.85): **{vs['count']}**")
    if vs["examples"]:
        lines += [""] + [f"- `{p}`" for p in vs["examples"][:10]] + [""]
    lines += [
        "",
        f"Global code similarity (minhash Jaccard): **{comp['global_shingle_jaccard']}**",
        f"Distinctive-identifier Jaccard: **{comp['identifier_jaccard']}**",
    ]
    sr = comp["shared_rare_identifiers"]
    lines.append(f"Shared rare identifiers (length ≥ 10): **{sr['count']}**")
    if sr["examples"]:
        lines += ["", "Examples: " + ", ".join(f"`{x}`" for x in sr["examples"][:12]), ""]
    d = comp["dep_overlap"]
    lines += ["", f"Shared dependencies: **{d['count']}** " +
              (f"({', '.join(d['names'][:8])})" if d["names"] else "(none)")]
    lic = comp["license"]
    lines.append(f"License guess: {a} → {lic['a'] or 'unknown'}; "
                 f"{b} → {lic['b'] or 'unknown'}; "
                 f"byte-identical license file: {lic['byte_identical_license_file']}")
    ack = comp["acknowledgment_in_a"]
    if ack:
        lines += ["", f"**{a} acknowledges {b} in its docs:**"]
        lines += [f"- \"{s['quote']}\"" for s in ack]
    lines.append("")
    return "\n".join(lines)


def _timeline_section(ev):
    events = ev.get("timeline", [])
    if isinstance(events, dict):
        events = events.get("events", [])
    if not events:
        return "## Timeline\n\nNo date evidence available.\n"
    lines = ["## Timeline", ""]
    for e in events:
        lines.append(f"- {e['date'][:10]} — **{e['label']}** ({e.get('kind', '')})")
    direction = ev.get("timeline", {}).get("direction") if isinstance(ev.get("timeline"), dict) else None
    if direction:
        lines += ["", f"Reading: {direction}."]
    lines.append("")
    return "\n".join(lines)


def render_report(ev, title, mode="investigate"):
    L = [f"# Fossil investigation: {title}", ""]
    L.append(f"_Generated by Fossil {ev.get('fossil_version')} on "
             f"{(ev.get('created') or '')[:10]}. Case: `{ev.get('case_id')}`._")
    L.append("")

    if mode == "compare":
        v = ev["verdict"]
        L += ["## Verdict", "", f"**{_verdict_headline(v)}**", "", v.get("summary", ""), ""]
        for u in v.get("uncertainty") or []:
            if u:
                L.append(f"> Uncertainty: {u}")
        if any(v.get("uncertainty") or []):
            L.append("")
        L += [_compare_detail(ev)]
        # Project sketches
        for side in ("a", "b"):
            s = ev[side]
            meta = s.get("meta") or {}
            L += [f"### {s['label']}", "",
                  f"- Files: {s['files']}"]
            if s.get("languages"):
                top = ", ".join(f"{k} ({v_})" for k, v_ in list(s["languages"].items())[:5])
                L.append(f"- Languages: {top}")
            if meta.get("description"):
                L.append(f"- Description: {meta['description']}")
            if meta.get("html_url"):
                L.append(f"- {meta['html_url']}")
            L.append("")
        L.append(_timeline_section(ev))
        L += ["## Reproducibility", "",
              "Verdict thresholds used: " +
              ", ".join(f"{k}={v_}" for k, v_ in ev.get("thresholds", {}).items()),
              "",
              "Re-run with the same inputs to reproduce. Upstream repositories "
              "change over time; the evidence bundle (`evidence.json`) records the "
              "commit SHAs examined.",
              ""]
        return "\n".join(L)

    # investigate mode
    f = ev["finding"]
    L += ["## Finding", ""]
    if f["kind"] == "relationship_found":
        L += [f"**{_verdict_headline(f['verdict'])}**",
              "",
              f"Primary candidate: **{f['primary']}**",
              "",
              f["verdict"].get("summary", ""),
              ""]
    else:
        L += ["**No meaningful relationship found.**", "",
              f.get("summary", ""), ""]
        if f.get("checked"):
            L += ["Candidates tested and rejected:"]
            L += [f"- {c}" for c in f["checked"]]
            L.append("")

    L.append("## Candidates examined")
    L.append("")
    for r in ev.get("candidates", []):
        L.append(_candidate_section(r))

    sigs = ev.get("signals", [])
    if sigs:
        L += ["## Discovery signals", "",
              "What Fossil searched for (guesses, not facts):", ""]
        for s in sigs:
            L.append(f"- [{s['kind']}] `{s['value']}`")
        L.append("")

    t = ev["target"]
    L += ["## Target sketch", "",
          f"- **{t['label']}** — {t['files']} files"]
    if t.get("languages"):
        top = ", ".join(f"{k} ({v_})" for k, v_ in list(t["languages"].items())[:5])
        L.append(f"- Languages: {top}")
    meta = t.get("meta") or {}
    if meta.get("description"):
        L.append(f"- Description: {meta['description']}")
    if meta.get("html_url"):
        L.append(f"- {meta['html_url']}")
    if t.get("readme_signals"):
        L.append("- README self-reports:")
        for s in t["readme_signals"]:
            L.append(f"  - [{s['kind']}] \"{s['quote']}\" → `{s['target']}`")
    L.append("")
    L.append(_timeline_section(ev))
    L += ["## Method and limits", "",
          "- Deterministic comparison only: file hashes, token shingles, identifier "
          "vocabularies, manifests, licenses, git history. No LLM judgments.",
          "- Similarity is not ancestry: shared libraries, common templates, and "
          "convergent design are treated as alternative explanations first.",
          "- History depth is bounded by the clone depth; very old fork points may "
          "fall outside the examined commits (noted per-case in git metadata).",
          "- GitHub API data (creation dates, fork flags) is corroborating metadata, "
          "never the verdict by itself.",
          ""]
    return "\n".join(L)
